#!/usr/bin/env python3
"""Generates the reference data the docs render, from a real Hardcharger build.

    scripts/gen_reference.py            # regenerate src/data/* and the vendored pages
    scripts/gen_reference.py --check    # regenerate into a temporary copy; fail on any difference

What it asks the server and its client for:

- `hardcharger-server --print-options-json`       -> src/data/options.json (server configuration)
- `SELECT … FROM hardcharger_settings()`           -> src/data/settings.json (SET hardcharger.*)
- `duckdb_functions()` named hardcharger*          -> src/data/functions.json
- `GET /metrics` with --enable-metrics             -> src/data/metrics.json
- `hardcharger --help`, `.help`, `.mode` list      -> src/data/cli-help.txt, cli-dot-commands.txt

and what it copies from the source repositories (HARDCHARGER_DOCS_HARDCHARGER_SRC and
HARDCHARGER_DOCS_WARPSQL_SRC: checkouts of gizmodata/hardcharger and gizmodata/warp-sql):

- hardcharger/CHANGELOG.md   -> src/content/docs/reference/release-notes.md
- warp-sql/spec/warp-sql.md  -> src/content/docs/reference/warp-sql-protocol.md

The server binaries come from HARDCHARGER_DOCS_BIN_DIR. Nothing is optional: a missing
binary, checkout or answer fails the run.
"""

from __future__ import annotations

import argparse
import difflib
import json
import os
import pathlib
import re
import shutil
import signal
import socket
import subprocess
import sys
import tempfile
import time
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
GENERATED = [
    "src/data/server-version.json",
    "src/data/options.json",
    "src/data/settings.json",
    "src/data/functions.json",
    "src/data/metrics.json",
    "src/data/cli-help.txt",
    "src/data/cli-dot-commands.txt",
    "src/content/docs/reference/configuration.mdx",
    "src/content/docs/reference/release-notes.md",
    "src/content/docs/reference/warp-sql-protocol.md",
]
HEADER = "Generated by scripts/gen_reference.py from {source}. Do not edit: change the source and regenerate."


def env(name: str) -> str:
    value = os.environ.get(name)
    if not value:
        sys.exit(f"{name} is not set (see {pathlib.Path(__file__).name}'s docstring)")
    return value


def free_port() -> int:
    with socket.socket() as s:
        s.bind(("127.0.0.1", 0))
        return s.getsockname()[1]


class Server:
    """A throwaway hardcharger-server on free ports, in an empty directory and environment."""

    def __init__(self, bin_dir: pathlib.Path, *args: str):
        self.dir = pathlib.Path(tempfile.mkdtemp(prefix="hc-ref-"))
        self.port, self.health = free_port(), free_port()
        self.extra = list(args)
        self.env = {"PATH": "/usr/bin:/bin", "HOME": str(self.dir), "TMPDIR": str(self.dir),
                    "HARDCHARGER_ADMIN_PASSWORD": "reference-only"}
        self.bin_dir = bin_dir

    def __enter__(self) -> "Server":
        args = [str(self.bin_dir / "hardcharger-server"), "--host", "127.0.0.1", "--port", str(self.port),
                "--health-port", str(self.health), *self.extra]
        self.log = open(self.dir / "server.log", "wb")
        self.process = subprocess.Popen(args=args, cwd=self.dir, env=self.env, stdout=self.log,
                                        stderr=subprocess.STDOUT, start_new_session=True)
        deadline = time.monotonic() + 30
        while time.monotonic() < deadline:
            if self.process.poll() is not None:
                sys.exit(f"hardcharger-server exited: {(self.dir / 'server.log').read_text()}")
            try:
                with urllib.request.urlopen(f"http://127.0.0.1:{self.health}/health", timeout=1):
                    return self
            except Exception:
                time.sleep(0.1)
        sys.exit("hardcharger-server did not come up")

    def __exit__(self, *exc) -> None:
        os.killpg(self.process.pid, signal.SIGKILL)
        self.process.wait()
        shutil.rmtree(self.dir, ignore_errors=True)

    def client(self, *args: str) -> str:
        done = subprocess.run(
            args=[str(self.bin_dir / "hardcharger"), "--host", "127.0.0.1", "--port", str(self.port), "--tls=false",
                  "--username", "hardcharger", "--quiet", *args],
            env=dict(self.env, HARDCHARGER_PASSWORD="reference-only"), capture_output=True, text=True, timeout=60)
        if done.returncode != 0:
            sys.exit(f"hardcharger {' '.join(args)} failed: {done.stdout}{done.stderr}")
        return done.stdout

    def query_json(self, sql: str) -> list[dict]:
        return json.loads(self.client("--json", "--command", sql))


def options(bin_dir: pathlib.Path) -> str:
    done = subprocess.run(args=[str(bin_dir / "hardcharger-server"), "--print-options-json"],
                          capture_output=True, text=True, env={"PATH": "/usr/bin:/bin"})
    if done.returncode != 0:
        sys.exit(f"hardcharger-server --print-options-json failed ({done.returncode}): {done.stderr.strip()}\n"
                 "This build predates the export mode (gizmodata/hardcharger#1).")
    return json.dumps(json.loads(done.stdout), indent=2) + "\n"


def configuration_page(options_json: str) -> str:
    """The configuration reference as Markdown: real headings, so the table of contents, search
    and the link checker all see every option."""
    data = json.loads(options_json)
    groups: dict[str, list[dict]] = {}
    for option in data["options"]:
        groups.setdefault(option["group"], []).append(option)
    out = [f"{len(data['options'])} options in {len(groups)} groups: "
           + " · ".join(f"[{g}](#{re.sub(r'[^a-z0-9]+', '-', g.lower()).strip('-')})" for g in groups) + ".", ""]
    for group, options in groups.items():
        out += [f"## {group}", ""]
        for o in options:
            value = {"boolean": "", "integer": " <n>", "list": " <a,b,...>"}.get(o["type"], " <value>")
            default = o["default"] if o["default"] != "" else "(empty)"
            description = o["description"][0].upper() + o["description"][1:]
            if not description.endswith((".", ")")):
                description += "."
            for raw, safe in (("<", "&lt;"), (">", "&gt;"), ("{", "\\{"), ("}", "\\}"), ("*", "\\*")):
                description = description.replace(raw, safe)  # MDX: text, not markup
            out += [f"### `{o['name']}`", "", description, "",
                    "| | |", "|---|---|",
                    f"| Flag | `{o['flag']}{value}` |",
                    f"| Environment | `{o['env']}` |",
                    f"| YAML | `{o['yaml_key']}: …` |",
                    f"| Type | {o['type']} |",
                    f"| Default | `{default}` |", ""]
    template = (ROOT / "scripts" / "templates" / "configuration.mdx").read_text(encoding="utf-8")
    return template.replace("{{OPTIONS}}", "\n".join(out))


def settings(server: Server) -> str:
    rows = server.query_json(
        "SELECT name, scope, input_type, default_value, cli_flag, env_var, description "
        "FROM hardcharger_settings() ORDER BY scope, name")
    if not rows:
        sys.exit("hardcharger_settings() returned no rows")
    return json.dumps(rows, indent=2) + "\n"


def functions(server: Server) -> str:
    rows = server.query_json(
        "SELECT DISTINCT function_name AS name, function_type AS type, return_type "
        "FROM duckdb_functions() WHERE function_name ILIKE 'hardcharger%' ORDER BY type, name")
    if not rows:
        sys.exit("duckdb_functions() lists no hardcharger functions")
    for row in rows:
        if row["type"] == "table":
            row["columns"] = server.query_json(
                f"SELECT column_name AS name, column_type AS type FROM (DESCRIBE SELECT * FROM {row['name']}())")
    return json.dumps(rows, indent=2) + "\n"


def metrics(bin_dir: pathlib.Path) -> str:
    metrics_port = free_port()
    with Server(bin_dir, "--enable-metrics", "--metrics-port", str(metrics_port), "--metrics-bind-address",
                "127.0.0.1") as server:
        server.client("--command", "SELECT 1")
        deadline = time.monotonic() + 15
        while True:
            try:
                with urllib.request.urlopen(f"http://127.0.0.1:{metrics_port}/metrics", timeout=2) as response:
                    text = response.read().decode()
                break
            except Exception:
                if time.monotonic() > deadline:
                    sys.exit("/metrics did not answer")
                time.sleep(0.2)
    found: dict[str, dict] = {}
    for line in text.splitlines():
        m = re.match(r"# (HELP|TYPE) (\S+) (.*)", line)
        if m:
            entry = found.setdefault(m.group(2), {"name": m.group(2), "type": "", "help": "", "labels": []})
            entry["help" if m.group(1) == "HELP" else "type"] = m.group(3)
        elif line and not line.startswith("#"):
            m = re.match(r"([a-zA-Z_:][\w:]*)(?:\{([^}]*)\})?\s", line)
            if m:
                name = re.sub(r"_(bucket|sum|count)$", "", m.group(1)) if m.group(1) not in found else m.group(1)
                entry = found.setdefault(name, {"name": name, "type": "", "help": "", "labels": []})
                for label in re.findall(r'(\w+)="', m.group(2) or ""):
                    if label not in entry["labels"] and label != "le":
                        entry["labels"].append(label)
    rows = sorted(found.values(), key=lambda e: e["name"])
    if not rows:
        sys.exit("/metrics returned no metrics")
    return json.dumps(rows, indent=2) + "\n"


def cli_help(bin_dir: pathlib.Path) -> str:
    done = subprocess.run(args=[str(bin_dir / "hardcharger"), "--help"], capture_output=True, text=True,
                          env={"PATH": "/usr/bin:/bin", "HOME": tempfile.gettempdir()})
    if done.returncode != 0 or "Usage:" not in done.stdout:
        sys.exit(f"hardcharger --help failed: {done.stdout}{done.stderr}")
    return done.stdout


def cli_dot_commands(server: Server) -> str:
    text = server.client("--command", ".help")
    if ".mode" not in text:
        sys.exit(f".help did not list the dot commands: {text}")
    return text


def vendored(source: pathlib.Path, title: str, description: str, origin: str, drop_title: bool = True) -> str:
    text = source.read_text(encoding="utf-8")
    if drop_title:
        text = re.sub(r"\A# [^\n]*\n+", "", text)
    front = (f"---\ntitle: {json.dumps(title)}\ndescription: {json.dumps(description)}\n"
             f"editUrl: false\n---\n\n"
             f"{{/* {HEADER.format(source=origin)} */}}\n\n")
    return front + text


def generate(out: pathlib.Path) -> None:
    bin_dir = pathlib.Path(env("HARDCHARGER_DOCS_BIN_DIR")).resolve()
    hc_src = pathlib.Path(env("HARDCHARGER_DOCS_HARDCHARGER_SRC")).resolve()
    warp_src = pathlib.Path(env("HARDCHARGER_DOCS_WARPSQL_SRC")).resolve()
    files: dict[str, str] = {}
    files["src/data/options.json"] = options(bin_dir)
    files["src/content/docs/reference/configuration.mdx"] = configuration_page(files["src/data/options.json"])
    with Server(bin_dir, "--enable-metrics", "--metrics-port", "0", "--enable-instrumentation") as server:
        files["src/data/server-version.json"] = json.dumps(
            obj={"version": server.query_json(sql="SELECT HARDCHARGER_VERSION() AS version")[0]["version"]},
            indent=2,
        ) + "\n"
        files["src/data/settings.json"] = settings(server)
        files["src/data/functions.json"] = functions(server)
        files["src/data/cli-dot-commands.txt"] = cli_dot_commands(server)
    files["src/data/metrics.json"] = metrics(bin_dir)
    files["src/data/cli-help.txt"] = cli_help(bin_dir)
    files["src/content/docs/reference/release-notes.md"] = vendored(
        hc_src / "CHANGELOG.md", "Release notes",
        "Every Hardcharger release and what changed, from the server's CHANGELOG.",
        "gizmodata/hardcharger CHANGELOG.md")
    files["src/content/docs/reference/warp-sql-protocol.md"] = vendored(
        warp_src / "spec" / "warp-sql.md", "Warp SQL protocol",
        "The Warp SQL protocol specification, version 1.0.0: SQL over HTTP with Arrow IPC results.",
        "gizmodata/warp-sql spec/warp-sql.md")
    for rel, text in files.items():
        if rel.endswith("/release-notes.md") or rel.endswith("/warp-sql-protocol.md"):
            # MDX-safe: the vendored Markdown is rendered as .md, so only the comment needs care.
            text = text.replace("{/* ", "<!-- ").replace(" */}", " -->")
        target = out / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the committed files differ")
    args = parser.parse_args()
    if not args.check:
        generate(ROOT)
        print("\n".join(f"wrote {rel}" for rel in GENERATED))
        return 0
    with tempfile.TemporaryDirectory() as tmp:
        generate(pathlib.Path(tmp))
        drift = []
        for rel in GENERATED:
            fresh = (pathlib.Path(tmp) / rel).read_text(encoding="utf-8")
            committed_path = ROOT / rel
            committed = committed_path.read_text(encoding="utf-8") if committed_path.exists() else ""
            if fresh != committed:
                drift.append(rel)
                sys.stdout.writelines(difflib.unified_diff(
                    committed.splitlines(keepends=True), fresh.splitlines(keepends=True),
                    fromfile=f"committed/{rel}", tofile=f"generated/{rel}", n=1))
    if drift:
        print(f"\nThe reference drifted from the server in {len(drift)} file(s): {', '.join(drift)}.\n"
              "Run scripts/gen_reference.py and commit the result.", file=sys.stderr)
        return 1
    print(f"reference matches the server ({len(GENERATED)} files)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
